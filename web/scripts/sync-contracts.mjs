// Copies contract ABIs and deployment addresses from ../contracts into src/generated/contracts.ts.
// Run after `forge build` and after every deployment:  npm run sync-contracts
import { readFileSync, readdirSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const web = join(dirname(fileURLToPath(import.meta.url)), "..");
const contracts = join(web, "..", "contracts");

function abi(file, name) {
  const artifact = join(contracts, "out", file, `${name}.json`);
  if (!existsSync(artifact)) throw new Error(`Missing ${artifact} – run "forge build" in contracts/ first.`);
  return JSON.parse(readFileSync(artifact, "utf8")).abi;
}

const deploymentsDir = join(contracts, "deployments");
const deployments = {};
for (const file of readdirSync(deploymentsDir).filter((f) => f.endsWith(".json"))) {
  const d = JSON.parse(readFileSync(join(deploymentsDir, file), "utf8"));
  deployments[d.chainId] = d;
}

const out = `// Generated by scripts/sync-contracts.mjs – do not edit by hand.

export const btcYieldVaultAbi = ${JSON.stringify(abi("BtcYieldVault.sol", "BtcYieldVault"), null, 2)} as const;

export const oracleSwapperAbi = ${JSON.stringify(abi("OracleUniswapSwapper.sol", "OracleUniswapSwapper"), null, 2)} as const;

export const deployments = ${JSON.stringify(deployments, null, 2)} as const;
`;

mkdirSync(join(web, "src", "generated"), { recursive: true });
writeFileSync(join(web, "src", "generated", "contracts.ts"), out);
console.log(`Synced ABIs and deployments for chains: ${Object.keys(deployments).join(", ") || "none"}`);
